export const lessons: Lesson[] = studyDays.map((day) => {
  const live = liveLessons.find((lesson) => lesson.dayId === day.id);
  if (live) return live;
  const extra = stubExtras[day.id];
  const blocks: Lesson["blocks"] = [
    { type: "p", text: day.blurb },
    {
      type: "callout",
      callout: {
        tone: "exam",
        title: day.status === "paper" ? "试卷日占位" : "本日内容即将补全",
        body:
          extra?.extra ??
          (day.status === "paper"
            ? "v1 提供 150 分钟计时与完成本日。完整真题卷不在本版本范围内。"
            : "路线已按《软件设计师教程》第5版章节序排好。本日精讲稍后补全；可先看标题与提要。"),
      },
    },
  ];
  if (day.holiday) {
    blocks.push({
      type: "p",
      text:
        day.holiday === "mid-autumn"
          ? "中秋假期：按短训处理，不要改成长会话。"
          : "国庆假期：能短则短。试卷日仍按试卷节奏计时。",
    });
  }
  if (day.makeup) {
    blocks.push({
      type: "p",
      text: "调休工作日：按 45 分钟工作日，只复盘，不开 90/150 分钟长会话。",
    });
  }
  return {
    dayId: day.id,
    title: day.title,
    minutes: day.durationMin,
    keyPoints: extra?.keyPoints ?? [
      day.topic,
      `${day.durationMin} 分钟 · ${day.kind === "paper" ? "试卷节奏" : "短训"}`,
    ],
    blocks,
  };
});

export function getLesson(dayId: string): Lesson | undefined {
  return lessons.find((lesson) => lesson.dayId === dayId);
}
